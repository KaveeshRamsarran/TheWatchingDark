// Packs the GLB files produced by tools/blender/build_models.py into js/assets.js as base64,
// so the game can load its models even when index.html is opened straight from disk.
// Usage: node tools/pack_assets.mjs <glb_dir> js/assets.js
import fs from 'node:fs';
import path from 'node:path';

const [, , dir = 'tools/build', out = 'js/assets.js'] = process.argv;
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.glb')).sort();
let js = '// GENERATED by tools/pack_assets.mjs from tools/blender/build_models.py - do not edit by hand.\n';
js += 'window.TWD_ASSETS = {\n';
for (const f of files) {
    const b64 = fs.readFileSync(path.join(dir, f)).toString('base64');
    js += `    ${JSON.stringify(path.basename(f, '.glb'))}: ${JSON.stringify(b64)},\n`;
    console.log(f, (b64.length / 1024).toFixed(0) + ' KB');
}
js += '};\n';
fs.writeFileSync(out, js);
console.log('wrote', out, (js.length / 1024 / 1024).toFixed(2) + ' MB');
